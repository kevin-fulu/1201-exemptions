// lib.mjs — shared helpers for the §1201 data-layer build pipeline.
// Node stdlib only.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const A = (p) => path.join(ROOT, p);

export const readJSON = (p) => JSON.parse(fs.readFileSync(A(p), "utf8"));
export const writeJSON = (p, obj) => fs.writeFileSync(A(p), JSON.stringify(obj, null, 2) + "\n");
export const readText = (p) => fs.readFileSync(A(p), "utf8");
export const writeText = (p, s) => fs.writeFileSync(A(p), s);

export const GRANT_STATUSES = new Set(["new", "renewed_unchanged", "renewed_expanded", "renewed_narrowed"]);
export const DENIAL_STATUSES = new Set(["petitioned_denied", "petitioned_denied_procedural", "petitioned_denied_de_minimis"]);

// ---- Layer 1 -------------------------------------------------------------
export function loadLayer1(cycles) {
  const grants = {}, denials = {}, byId = {};
  for (const y of cycles) {
    grants[y] = readJSON(`analysis/cycle-${y}.json`).exemptions;
    denials[y] = readJSON(`analysis/cycle-${y}-denials.json`).denials;
    for (const r of grants[y]) byId[r.class_id] = { ...r, cycle: y, kind: "grant" };
    for (const r of denials[y]) byId[r.class_id] = { ...r, cycle: y, kind: "denial" };
  }
  return { grants, denials, byId };
}

// ---- derived status grid -------------------------------------------------
// A lineage's members[] list only the cycles where it was codified or
// petitioned-and-denied. The full per-cycle status grid is derived:
//   grant lineage  — not_yet_proposed before its first grant (incl. cycles
//                    after a failed petition), not_renewed for later gaps;
//   denial lineage — not_proposed for every non-member cycle.
export function deriveGrid(lineage, cycles) {
  const byCycle = {};
  for (const m of lineage.members) byCycle[m.cycle] = m;
  const firstGrant = lineage.members.find((m) => GRANT_STATUSES.has(m.status));
  const firstGrantCycle = firstGrant ? firstGrant.cycle : null;
  return cycles.map((y) => {
    const m = byCycle[y];
    if (m) return m.status;
    if (lineage.kind === "denial") return "not_proposed";
    return firstGrantCycle !== null && y >= firstGrantCycle ? "not_renewed" : "not_yet_proposed";
  });
}

